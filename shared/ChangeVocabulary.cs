namespace CollegeLMS.Shared;

/// <summary>
/// Словарь терминов CollegeLMS для поверхностей без веб-клиента: бот MAX и
/// PNG-корректировка.
///
/// Файл один на все проекты и подключается в них ссылкой
/// (<c>&lt;Compile Include&gt;</c>), а не копируется. Копия была бы третьей
/// после веба и миниаппа — то есть ровно тем дублированием, которое
/// расходилось по формулировкам: одно изменение называлось «Добавлено»,
/// «добавлена» и «Изменено» в зависимости от поверхности, а знак переноса
/// был <c>→</c> на вебе и в PNG и <c>=&gt;</c> в MAX и боте.
///
/// Источник истины для веб-части — <c>CollegeLMS.Next/lib/change-tags.ts</c>.
/// Модуль намеренно не знает ни про типы API, ни про TypeScript: на вход
/// строка, потому что бот получает тип изменения строкой.
/// </summary>
public static class ChangeVocabulary
{
    /// <summary>
    /// Знак изменения в строке позиции.
    ///
    /// В чате ASCII-стрелка предпочтительнее ещё и потому, что <c>→</c> в
    /// разных шрифтах отображается по-разному, а чат рисуется чужим шрифтом.
    /// </summary>
    public const string ChangeArrow = "=>";

    /// <summary>Исход операции так, как его показывает читатель расписания.</summary>
    public static string Label(string changeType) =>
        changeType switch
        {
            "Remove" => "Снято",
            // Замена и перенос — это добавление со снимаемым занятием, поэтому
            // для читателя расписания это добавление. Исходная операция видна
            // только в журнале преподавателя, где подписи свои.
            "Add" or "Replace" or "Move" => "Добавлено",
            _ => "Изменено",
        };
}
